import assert from 'node:assert/strict';
import {observedQuoteChanges} from '../lib/nba-observed-changes.mjs';
const record=(capture,update,odds)=>({capturedAt:capture,sourceUpdatedAt:update,americanOdds:odds});
const a=record('2026-11-21T16:00:00Z','2026-11-21T15:55:00Z',-110);
const b=record('2026-11-21T16:30:00Z','2026-11-21T16:25:00Z',-120);
const c=record('2026-11-21T17:00:00Z','2026-11-21T16:25:00Z',-130);
const result=observedQuoteChanges([c,a,b]);
assert.equal(result.length,2);
assert.equal(result[0].status,'observed_change');
assert.equal(result[0].elapsedMinutes,30);
assert.equal(result[0].fromSourceAgeMinutes,5);
assert.equal(result[0].toSourceAgeMinutes,5);
assert.equal(result[1].toSourceAgeMinutes,35);
assert.equal(result[0].rawImpliedProbabilityChangePoints,2.16);
assert.equal(result[1].status,'unconfirmed_source_timestamp');
assert.equal(result[1].sourceUpdateAdvanced,false);
assert.equal(observedQuoteChanges([a,a]).length,0);
assert.equal(observedQuoteChanges([a,record('2026-11-21T16:30:00Z','2026-11-21T16:25:00Z',-110)]).length,0);
assert.deepEqual(observedQuoteChanges([a,record('2026-11-21T16:30:00Z','2026-11-21T16:31:00Z',-120)]),[],'future source updates cannot be accepted');
assert.deepEqual(observedQuoteChanges([record('2026-11-21T16:00:00Z','2026-11-21T16:01:00Z',-110),b]),[],'future updates at the earlier endpoint are invalid');
assert.equal(observedQuoteChanges([a,null,b]).length,1,'invalid entries do not crash observed-change analysis');
assert.equal(observedQuoteChanges([a,record('2026-11-21T16:15:00Z','2026-11-21T16:16:00Z',-125),b]).length,0,'timestamped invalid intervening quote blocks claims of adjacent observed changes');
assert.deepEqual(observedQuoteChanges([a,record('2026-11-21T16:00:00Z','2026-11-21T15:58:00Z',-115),b]),[],'ambiguous duplicate capture time blocks adjacent price-change claims');
assert.deepEqual(observedQuoteChanges([a,{capturedAt:0,sourceUpdatedAt:0,americanOdds:-120},b]).length,1,'numeric timestamps cannot be treated as verified quote captures');
assert.equal(observedQuoteChanges([a,record('2026-11-21T16:15:00','2026-11-21T16:10:00Z',-125),b]).length,0,'timezone-free capture cannot establish adjacent evidence');
assert.equal(observedQuoteChanges([a,record('2026-11-21T16:15:00Z','2026-11-21T16:10:00',-125),b]).length,0,'timezone-free source timestamp blocks adjacent evidence');
assert.deepEqual(observedQuoteChanges([]),[]);
assert.throws(()=>observedQuoteChanges(null),/Expected accepted/);
console.log('NBA observed change classifications passed');
