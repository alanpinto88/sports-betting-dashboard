import assert from 'node:assert/strict';
import {nbaChangesCsv} from '../lib/nba-changes-csv.mjs';
const selection={eventId:'e1',playerName:'=unsafe',book:'book',market:'player_points',side:'Over',line:20.5};
const changes=[{fromCapturedAt:'2026-11-21T16:00:00Z',toCapturedAt:'2026-11-21T16:30:00Z',elapsedMinutes:30,fromSourceAgeMinutes:5,toSourceAgeMinutes:35,fromOdds:-110,toOdds:-120,rawImpliedProbabilityChangePoints:2.16,sourceUpdateAdvanced:true,sourceTimestampRegressed:false,status:'observed_change'}];
const csv=nbaChangesCsv(changes,selection);
assert.match(csv,/source_timestamp_advanced,source_timestamp_regressed,evidence_status/);
assert.match(csv,/"true","false","observed_change"/);
assert.match(nbaChangesCsv([{...changes[0],sourceUpdateAdvanced:false,sourceTimestampRegressed:true,status:'regressed_source_timestamp'}],selection),/"false","true","regressed_source_timestamp"/);
assert.match(csv,/elapsed_minutes,exceeds_gap_threshold,from_source_age_minutes,to_source_age_minutes/);
assert.match(nbaChangesCsv(changes,selection,20),/"30","true","5","35","-110"/);
assert.match(nbaChangesCsv(changes,selection,60),/"30","false","5","35","-110"/);
assert.throws(()=>nbaChangesCsv(changes,selection,0),/Invalid gap threshold/);
assert.match(csv,/"-110","-120"/);
assert.match(csv,/"'=unsafe"/);
assert.match(csv,/"observed_change"/);
assert.equal(nbaChangesCsv([],selection).trim().split('\n').length,1);
assert.throws(()=>nbaChangesCsv([{...changes[0],elapsedMinutes:-2}],selection),/Invalid observed change/);
assert.throws(()=>nbaChangesCsv([{...changes[0],sourceTimestampRegressed:true}],selection),/Invalid observed change/);
assert.throws(()=>nbaChangesCsv([{...changes[0],sourceUpdateAdvanced:false,status:'observed_change'}],selection),/Invalid observed change/);
assert.throws(()=>nbaChangesCsv([{...changes[0],status:'unconfirmed_source_timestamp'}],selection),/Invalid observed change/);
assert.throws(()=>nbaChangesCsv([{...changes[0],fromCapturedAt:0}],selection),/Invalid observed change/);
assert.throws(()=>nbaChangesCsv([{...changes[0],toCapturedAt:'2026-11-21T15:00:00Z'}],selection),/Invalid observed change/);
assert.throws(()=>nbaChangesCsv([{...changes[0],elapsedMinutes:31}],selection),/Invalid observed change/);
console.log('NBA change CSV evidence and spreadsheet formula protection passed');
